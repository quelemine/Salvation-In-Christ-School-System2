/**
 * UserAccountPage — /users/account/student/:studentId
 *
 * After approving a student, admin:
 *  1. Reviews student info
 *  2. Auto-generates credentials (email + password)
 *  3. Creates the login account
 *  4. Delivers credentials via: Print · WhatsApp · SMS (tel:)
 */
import { useEffect, useState } from 'react';
import { useParams, Link } from 'react-router-dom';
import api from '../services/api';
import { authService } from '../services/authService';
import { useSettingsStore } from '../store/settingsStore';

// ── Types ─────────────────────────────────────────────────────────────────────
interface StudentRecord {
  id: number;
  student_id: string;
  first_name: string;
  last_name: string;
  gender: string;
  date_of_birth: string;
  nationality: string;
  county: string;
  address: string;
  grade_applying_for: string;
  father_name: string;
  mother_name: string;
  father_contact: string;
  mother_contact: string;
  application_status: string;
  class?: { id: number; name: string; section?: string };
  user?: { id: number; email: string; user_code: string; is_active: boolean; role?: { name: string } };
}

interface Role { id: number; name: string; slug: string; }

interface SavedCredentials {
  userCode: string;
  fullName: string;
  email: string;
  password: string;
  role: string;
  phone: string;
  studentId: string;
  schoolName: string;
  schoolPhone: string;
  schoolAddress: string;
}

// ── Helpers ───────────────────────────────────────────────────────────────────
function StrengthBar({ pw }: { pw: string }) {
  if (!pw) return null;
  let s = 0;
  if (pw.length >= 8)          s++;
  if (/[A-Z]/.test(pw))        s++;
  if (/[0-9]/.test(pw))        s++;
  if (/[^A-Za-z0-9]/.test(pw)) s++;
  const c = ['', 'bg-rose-400', 'bg-amber-400', 'bg-cyan-500', 'bg-emerald-500'];
  const l = ['', 'Weak', 'Fair', 'Good', 'Strong'];
  return (
    <div className="mt-1.5 space-y-0.5">
      <div className="flex gap-1">{[1,2,3,4].map(i => <div key={i} className={`h-1.5 flex-1 rounded-full ${i<=s?c[s]:'bg-slate-200'}`}/>)}</div>
      <p className="text-xs text-slate-400">Strength: <strong>{l[s]}</strong></p>
    </div>
  );
}

